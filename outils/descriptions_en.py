TRADUCTION = {texte: en for (_, texte, _), en in zip(fr.SORTES, SORTES_EN)}
TRADUCTION.update({fr.RAYONS[k]: v for k, v in RAYONS_EN.items()})


def decrire_en(p: dict) -> str:
    trouve = fr.sorte(p["nom"])
    texte = trouve[0] if trouve else fr.RAYONS.get(p["rayon"], fr.RAYONS["Autres produits"])
    phrases = [TRADUCTION.get(texte, "")]
    car = p.get("caracteristiques", {})
    if car.get("Marque") and fr.normal(car["Marque"]) not in fr.normal(texte):
        phrases.append(f"Brand: {car['Marque']}.")
    if car.get("Origine"):
        phrases.append(f"Origin: {car['Origine']}.")
    if p.get("conditionnements"):
        n = len(p["conditionnements"])
        phrases.append(f"Available in {n} sizes: " + ", ".join(p["conditionnements"]) + ".")
    if p.get("couleurs"):
        n = len(p["couleurs"])
        phrases.append(f"Available in {n} colour{'s' if n > 1 else ''}: see the list below.")
    if p.get("unite"):
        phrases.append("Sold by weight, weighed in store to the quantity you want.")
    return " ".join(x for x in phrases if x)
